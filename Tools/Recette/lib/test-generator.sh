# Generate tests for all errors in a session
generate_tests_for_session() {
    local session_id="$1"

    local session_dir="${RECETTE_BASE:-.recette}/sessions/$session_id"
    local state_file="$session_dir/state.yaml"

    if [[ ! -f "$state_file" ]]; then
        echo "Session not found: $session_id"
        return 1
    fi

    if ! command -v yq &>/dev/null; then
        echo "yq required for test generation"
        return 1
    fi

    # Get all errors from session
    local error_count
    error_count=$(yq e '.errors_detected | length' "$state_file")

    local generated=0

    for ((i=0; i<error_count; i++)); do
        local error
        error=$(yq e ".errors_detected[$i]" "$state_file" -o json)

        local error_id error_type description
        error_id=$(echo "$error" | jq -r '.id')
        error_type=$(echo "$error" | jq -r '.type')
        description=$(echo "$error" | jq -r '.description')

        # Generate tests
        local tests
        tests=$(generate_tests_from_error "$error_id" "$error_type" "$description")

        # Update session state with generated test paths
        while IFS= read -r test_line; do
            local type="${test_line%%:*}"
            local path="${test_line#*:}"

            case "$type" in
                unit)
                    yq e -i "(.errors_detected[$i]).generated_tests.unit = \"$path\"" "$state_file"
                    ;;
                functional)
                    yq e -i "(.errors_detected[$i]).generated_tests.functional = \"$path\"" "$state_file"
                    ;;
                behat)
                    yq e -i "(.errors_detected[$i]).generated_tests.behat = \"$path\"" "$state_file"
                    ;;
            esac

            # Register in regression suite
            register_regression_test "$error_id" "$path" "$type"

            generated=$((generated + 1))
        done <<< "$tests"
    done

    echo "Generated $generated tests for $error_count errors"
}

